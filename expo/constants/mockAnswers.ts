export function getMockAnswer(question: string, age: KidAge): MockResponse {
  const normalized = question.trim().toLowerCase();
  const match = MOCK_ANSWERS.find((m) =>
    m.keywords.some((kw) => normalized.includes(kw.toLowerCase()))
  );

  if (match) {
    const byAge = match.byAge[age];
    return {
      answer: byAge.answer,
      followUp: byAge.followUp,
      parentPrompt: byAge.parentPrompt,
      topic: match.topic,
      images: match.images.map((img) => ({ ...img, source: 'mock' as const })),
    };
  }

  const fb = FALLBACK[age];
  return {
    answer: fb.answer,
    followUp: fb.followUp,
    parentPrompt: fb.parentPrompt,
    topic: 'כללי',
    images: [],
  };
}

